CREATE TABLE deck (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    description VARCHAR(255),
    created_at TIMESTAMP,
    view_count BIGINT,
    app_user_id BIGINT NOT NULL,

    CONSTRAINT fk_deck_app_user
        FOREIGN KEY (app_user_id)
        REFERENCES app_user(id)
);
